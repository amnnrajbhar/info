  /* ================= HERO ================= */
  const GLYPHS = "!<>-_\\/[]{}—=+*^?#01";
  function scramble(el, delay = 0) {
    const final = el.dataset.text;
    if (REDUCED) { el.textContent = final; return; }
    let t0 = 0;
    const queue = [...final].map((ch, i) => ({ ch, start: Math.floor(Math.random() * 12) + i * 2, end: Math.floor(Math.random() * 12) + 18 + i * 3 }));
    setTimeout(function tick(now) {
      // time-based (60fps-equivalent frames) so it finishes on time on slow devices
      if (!t0) t0 = performance.now();
      const frame = Math.floor((performance.now() - t0) / 16.7);
      let out = "", done = 0;
      for (const q of queue) {
        if (frame >= q.end) { out += q.ch; done++; }
        else if (frame >= q.start) out += GLYPHS[Math.floor(Math.random() * GLYPHS.length)];
        else out += " ";
      }
      el.textContent = out;
      if (done < queue.length) requestAnimationFrame(tick);
    }, delay);
  }

